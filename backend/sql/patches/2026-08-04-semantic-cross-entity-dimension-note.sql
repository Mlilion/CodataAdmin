-- 该字段是**纯人工维护**的，代码里没有任何自动填充（indicator/service.py 没有，
-- 别处也没有）。检索取数的校验器规则 2 拿它当**硬白名单**，不在名单里的维度
-- 一律报 dimension_allowed 拒绝，压根走不到 JOIN 编译那一步。
